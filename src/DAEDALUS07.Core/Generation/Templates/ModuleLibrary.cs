    private static readonly Dictionary<string, string[]> Cache = new(StringComparer.OrdinalIgnoreCase);

    public static string[] Rotate90(string[] module)
    {
        int size = module.Length;
        char[][] rotated = new char[size][];
        for (int i = 0; i < size; i++) rotated[i] = new char[size];

        for (int r = 0; r < size; r++)
        {
            for (int c = 0; c < size; c++)
            {
                rotated[c][size - 1 - r] = module[r][c];
            }
        }

        return rotated.Select(row => new string(row)).ToArray();
    }

    public static string[] GetVariant(string moduleCode)
    {
        if (string.IsNullOrWhiteSpace(moduleCode) || moduleCode == "--")
            return EmptyModule;

        moduleCode = moduleCode.Trim();

        if (Cache.TryGetValue(moduleCode, out var cached))
            return cached;

        char lastChar = char.ToUpperInvariant(moduleCode[^1]);
        int rotations = 0;
        string baseCode = moduleCode;

        if (moduleCode.Length >= 3 && lastChar is 'N' or 'E' or 'S' or 'W')
        {
            baseCode = moduleCode[..^1];
            rotations = lastChar switch
            {
                'N' => 0,
                'E' => 1,
                'S' => 2,
                'W' => 3,
                _   => 0
            };
        }

        string[] raw = GetBaseVariant(baseCode);
        if (raw == EmptyModule)
            return EmptyModule;

        string[] result = raw;
        for (int i = 0; i < rotations; i++)
        {
            result = Rotate90(result);
        }

        Cache[moduleCode] = result;
        return result;
    }

    private static string[] GetBaseVariant(string baseCode)
    {
        if (Modules.TryGetValue(baseCode, out var variant))
            return variant;

        if (baseCode.Length == 2 && char.IsLetter(baseCode[0]) && char.IsDigit(baseCode[1]))
        {
            string paddedCode = $"{baseCode[0]}0{baseCode[1]}";
            if (Modules.TryGetValue(paddedCode, out var paddedVariant))
                return paddedVariant;
        }

        if (baseCode.Length == 1 && char.IsLetter(baseCode[0]))
        {
            string singlePadded = $"{char.ToUpper(baseCode[0])}01";
            if (Modules.TryGetValue(singlePadded, out var sVariant))
                return sVariant;
        }

        if (baseCode.Equals("X1", StringComparison.OrdinalIgnoreCase) || baseCode.Equals("X", StringComparison.OrdinalIgnoreCase))
            return Modules["F01"];

        return EmptyModule;
    }
